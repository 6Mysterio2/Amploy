test('extension functions capture structured job and fill only reviewed empty visible fields',{timeout:30000},async()=>{
 const browser=await chromium.launch({executablePath,headless:true,args:['--no-sandbox']});
 try {
  const page=await browser.newPage();
  await page.route('http://127.0.0.1:32123/**',r=>r.fulfill({contentType:'text/html',body:`<html><body><script type="application/ld+json">{"@type":"JobPosting","title":"Engineer","hiringOrganization":{"name":"Example"},"description":"<p>Build useful things</p>"}</script><main><h1>Engineer</h1><form><label>Full name<input name="fullName"></label><label>Email<input type="email" name="email"></label><label>City<input name="city"></label><label>Phone<input name="phone" value="existing"></label><label>Password<input type="password" name="password"></label><input type="hidden" name="secret"><input name="hiddenEmail" type="email" style="display:none"><button>Submit</button></form></main></body></html>`}));
  await page.goto('http://127.0.0.1:32123/fixture');
  await page.evaluate(()=>{window.inputEvents=0;window.submits=0;document.addEventListener('input',()=>window.inputEvents++);document.querySelector('form').addEventListener('submit',e=>{e.preventDefault();window.submits++;});});
  const job=await page.evaluate(captureJob);assert.equal(job.title,'Engineer');assert.equal(job.company,'Example');assert.equal(job.description,'Build useful things');
  const discovered=await page.evaluate(collectFields);
  assert.deepEqual(discovered.fields.map(f=>f.name),['fullName','email','city']);
  const profile={fullName:'Alex Taylor',email:'alex@example.test',addressCity:'Hong Kong'};
  const fields=discovered.fields.map(f=>({...f,...suggestField(f,profile)}));
  const result=await page.evaluate(fillFields,{url:discovered.url,fields});assert.equal(result.filled,3);
  assert.equal(await page.locator('[name="email"]').inputValue(),profile.email);
  assert.equal(await page.locator('[name="phone"]').inputValue(),'existing');
  assert.equal(await page.locator('[name="password"]').inputValue(),'');
  assert.equal(await page.evaluate(()=>window.submits),0);assert.equal(await page.evaluate(()=>window.inputEvents),3);
  assert.equal((await page.evaluate(fillFields,{url:discovered.url,fields})).filled,0);
 } finally {await browser.close();}
});
